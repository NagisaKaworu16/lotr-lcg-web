"""Compress the mirrored card art to WebP and regenerate local-image-map.js.

png/jpg originals from scripts/fetch-card-images.py are large (about 275 KB per
card face). WebP at quality 80 keeps the 425x600 art visually identical while
cutting the repository footprint by roughly 80 percent.

Usage:
    python scripts/optimize-card-images.py            # convert everything
    python scripts/optimize-card-images.py --quality 78
"""
import argparse
import io
import json
import os
import re
import sys
import urllib.parse

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = os.path.join(ROOT, 'local-image-map.js')
RINGSDB_RE = re.compile(r'https://ringsdb\.com/bundles/cards/([0-9A-Za-z_-]+\.(?:png|jpg))')
BEORN_RE = re.compile(r'https://hallofbeorn\.com/Images/Cards/[^"\']+')

# url prefix -> folder holding the mirrored files
SOURCES = [
    ('https://ringsdb.com/bundles/cards/', 'assets/cards-en'),
    ('https://hallofbeorn.com/Images/Cards/', 'assets/cards-encounter'),
]


def read(path):
    with io.open(os.path.join(ROOT, path), encoding='utf-8') as fh:
        return fh.read()


def slug(url):
    raw = urllib.parse.unquote(url.rsplit('/', 1)[-1])
    stem, dot, ext = raw.rpartition('.')
    if not dot:
        stem, ext = raw, 'jpg'
    stem = re.sub(r'[^0-9A-Za-z]+', '-', stem).strip('-').lower()
    return f'{stem}.{ext.lower()}'


def targets():
    items = []
    for name in sorted(set(RINGSDB_RE.findall(read('image-index.js')))):
        items.append((f'https://ringsdb.com/bundles/cards/{name}', f'assets/cards-en/{name}'))
    for url in sorted(set(BEORN_RE.findall(read('encounter-image-index.js')))):
        items.append((url, f'assets/cards-encounter/{slug(url)}'))
    return items


def existing_map():
    if not os.path.exists(MAP):
        return {}
    with io.open(MAP, encoding='utf-8') as fh:
        text = fh.read()
    try:
        return json.loads(text[text.index('{'):text.rindex('}') + 1])
    except (ValueError, IndexError):
        return {}


def fit(im, max_side):
    w, h = im.size
    if max(w, h) <= max_side:
        return im
    scale = max_side / float(max(w, h))
    return im.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)


def convert(path, quality, max_side):
    stem, ext = os.path.splitext(path)
    if ext.lower() == '.webp':
        with Image.open(path) as im:
            if max(im.size) <= max_side:
                return path
            out = fit(im.convert('RGB'), max_side)
        out.save(path, 'WEBP', quality=quality, method=6)
        return path
    dest = stem + '.webp'
    with Image.open(path) as im:
        out = fit(im.convert('RGB'), max_side)
        out.save(dest, 'WEBP', quality=quality, method=6)
    if os.path.getsize(dest) < os.path.getsize(path):
        os.remove(path)
        return dest
    os.remove(dest)
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--quality', type=int, default=80)
    ap.add_argument('--max-side', type=int, default=620,
                    help='cap the long edge; core art is 600 so larger scans add no detail')
    args = ap.parse_args()

    before = after = converted = 0
    for _, folder in SOURCES:
        full = os.path.join(ROOT, folder.replace('/', os.sep))
        if not os.path.isdir(full):
            continue
        for name in sorted(os.listdir(full)):
            if not name.lower().endswith(('.png', '.jpg', '.jpeg', '.webp')):
                continue
            path = os.path.join(full, name)
            before += os.path.getsize(path)
            was = os.path.splitext(name)[1].lower()
            out = convert(path, args.quality, args.max_side)
            after += os.path.getsize(out)
            if os.path.splitext(out)[1].lower() != was:
                converted += 1

    # Keep the original remote URL as the key so image-index.js keeps working;
    # only the file extension changes when a png/jpg became webp.
    # Rebuild the map from the URLs the page actually references, so the keys
    # can never drift when a file changes extension.
    mapping = {}
    for url, rel in targets():
        stem = os.path.splitext(rel)[0]
        for ext in ('.webp', '.png', '.jpg', '.jpeg'):
            candidate = stem + ext
            if os.path.exists(os.path.join(ROOT, candidate.replace('/', os.sep))):
                mapping[url] = candidate
                break

    with io.open(MAP, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* Generated by scripts/fetch-card-images.py + optimize-card-images.py.\n')
        fh.write('   Mirrors RingsDB / Hall of Beorn art into assets/ so the offline\n')
        fh.write('   build never depends on those hosts at runtime. */\n')
        fh.write('const LOCAL_IMAGE_MAP=')
        json.dump(mapping, fh, ensure_ascii=False, indent=0, sort_keys=True)
        fh.write(';\n')
    print(f'converted={converted} entries={len(mapping)}')
    print(f'{before / 1e6:.1f} MB -> {after / 1e6:.1f} MB')
    return 0


if __name__ == '__main__':
    sys.exit(main())
