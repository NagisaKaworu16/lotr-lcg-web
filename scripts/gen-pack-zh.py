#!/usr/bin/env python3
"""Generate pack-zh.js from product-zh.json titles.

product-zh.json 是中文工作译名的唯一维护点（见 PROJECT_MEMORY：以银星计划
重置版／文景版体系为准，改表后重跑本脚本 + python build.py）。
file:// 下 fetch 会被 CORS 拦，所以浏览器侧需要 JS module（与
player-carddata.js 同一模式：生成文件、手改无效）。

Usage:
  python scripts/gen-pack-zh.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'product-zh.json')
OUT = os.path.join(ROOT, 'pack-zh.js')


def main():
    with open(SRC, encoding='utf-8') as f:
        data = json.load(f)
    titles = data.get('titles', {})
    lines = [
        '/* Generated by scripts/gen-pack-zh.py — product-zh.json titles 的 JS module 版。',
        '   中文工作译名（非官方）维护在 product-zh.json；改表后重跑本脚本 + python build.py。 */',
        'const PACK_ZH_TITLES={',
    ]
    for en, zh in titles.items():
        en_js = json.dumps(en, ensure_ascii=False)
        zh_js = json.dumps(zh, ensure_ascii=False)
        lines.append(f' {en_js}:{zh_js},')
    lines.append('};')
    lines.append('if(typeof module!=="undefined")module.exports=PACK_ZH_TITLES;')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'pack-zh.js: {len(titles)} titles written')


if __name__ == '__main__':
    main()
