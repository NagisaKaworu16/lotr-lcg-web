"""Download the card art the offline build references, so the page no longer
depends on ringsdb.com / hallofbeorn.com at runtime.

Both hosts are unreachable from mainland China. This script mirrors every
referenced image into assets/ and writes local-image-map.js, which image-ui.js
consults before falling back to the remote URL.

Usage (needs outbound network; --proxy if a local proxy is required):
    python scripts/fetch-card-images.py --proxy http://127.0.0.1:7899
    python scripts/fetch-card-images.py --proxy ... --limit 40   # smoke test
"""
import argparse
import concurrent.futures as futures
import io
import json
import os
import re
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RINGSDB_RE = re.compile(r'https://ringsdb\.com/bundles/cards/([0-9A-Za-z_-]+\.(?:png|jpg))')
BEORN_RE = re.compile(r'https://hallofbeorn\.com/Images/Cards/[^"\']+')
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/155 Safari/537.36'


def read(path):
    with io.open(os.path.join(ROOT, path), encoding='utf-8') as fh:
        return fh.read()


def slug(url):
    """Stable, filesystem-safe name for a hallofbeorn card face."""
    raw = urllib.parse.unquote(url.rsplit('/', 1)[-1])
    stem, dot, ext = raw.rpartition('.')
    if not dot:
        stem, ext = raw, 'jpg'
    stem = re.sub(r'[^0-9A-Za-z]+', '-', stem).strip('-').lower()
    return f'{stem}.{ext.lower()}'


def targets():
    items = []
    for name in sorted(set(RINGSDB_RE.findall(read('image-index.js')))):
        url = f'https://ringsdb.com/bundles/cards/{name}'
        items.append((url, f'assets/cards-en/{name}'))
    for url in sorted(set(BEORN_RE.findall(read('encounter-image-index.js')))):
        items.append((url, f'assets/cards-encounter/{slug(url)}'))
    return items


def fetch(opener, job):
    url, rel = job
    dest = os.path.join(ROOT, rel.replace('/', os.sep))
    if os.path.exists(dest) and os.path.getsize(dest) > 2048:
        return url, rel, 'cached', os.path.getsize(dest)
    last = None
    for _ in range(3):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': UA, 'Referer': 'https://ringsdb.com/'})
            with opener.open(req, timeout=45) as resp:
                data = resp.read()
            if resp.status != 200 or len(data) < 1024:
                raise IOError(f'HTTP {resp.status} / {len(data)} bytes')
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, 'wb') as fh:
                fh.write(data)
            return url, rel, 'ok', len(data)
        except Exception as exc:  # noqa: BLE001 - report and retry
            last = exc
    return url, rel, f'FAIL {last}', 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--proxy', default=os.environ.get('HTTPS_PROXY') or '')
    ap.add_argument('--workers', type=int, default=12)
    ap.add_argument('--limit', type=int, default=0)
    args = ap.parse_args()

    jobs = targets()
    if args.limit:
        jobs = jobs[:args.limit]
    print(f'images to sync: {len(jobs)}')

    handlers = {'http': args.proxy, 'https': args.proxy} if args.proxy else {}
    opener = urllib.request.build_opener(urllib.request.ProxyHandler(handlers))

    done = failed = 0
    mapping = {}
    with futures.ThreadPoolExecutor(max_workers=args.workers) as pool:
        for url, rel, status, size in pool.map(lambda j: fetch(opener, j), jobs):
            if status.startswith('FAIL'):
                failed += 1
                print(f'  ! {url} -> {status}')
            else:
                done += 1
                mapping[url] = rel
                if done % 100 == 0:
                    print(f'  ... {done}/{len(jobs)}')
    print(f'downloaded/cached={done} failed={failed}')

    # Keep previously known entries so an interrupted run never loses coverage.
    map_path = os.path.join(ROOT, 'local-image-map.js')
    previous = {}
    if os.path.exists(map_path):
        old = read('local-image-map.js')
        body = old[old.index('{'):old.rindex('}') + 1]
        try:
            previous = json.loads(body)
        except ValueError:
            previous = {}
    previous.update(mapping)
    previous = {u: p for u, p in sorted(previous.items())
                if os.path.exists(os.path.join(ROOT, p.replace('/', os.sep)))}
    with io.open(map_path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* Generated by scripts/fetch-card-images.py - remote art mirrored into assets/. */\n')
        fh.write('const LOCAL_IMAGE_MAP=')
        json.dump(previous, fh, ensure_ascii=False, indent=0, sort_keys=True)
        fh.write(';\n')
    print(f'local-image-map.js entries={len(previous)}')
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
